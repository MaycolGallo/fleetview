const descriptionMap: { [key: string]: string } = {
    '4': 'Ralenti',
    '5': 'Estacionado',
    '6': 'Transitando'
};


export async function POST(req: NextRequest) {
  try {
    const { vehicleId } = await req.json();

    const segments: RouteSegment[] = newVehicleHistoryData.groups.map((group: any) => {
      let records = group.records;
      if (!records || records.length === 0) {
          if (group.start_coords && group.end_coords) {
             const [startLat, startLng] = group.start_coords.split(',').map(Number);
             records = [
                {
                    coordenadas: group.start_coords,
                    fecha: Math.floor(Date.now()/1000) - 1000,
                    param1: group.id_estado === '6' ? 'Parked' : 'Idle',
                },
                {
                    coordenadas: group.end_coords,
                    fecha: Math.floor(Date.now()/1000),
                    param1: group.id_estado === '6' ? 'Parked' : 'Idle',
                }
             ];
          } else {
            return null;
          }
      }
      const firstRecord = records[0];
      const lastRecord = records[records.length - 1];

      return {
        id_estado: group.id_estado,
        description: descriptionMap[group.id_estado as keyof typeof descriptionMap] || 'Unknown',
        durationMinutes: group.total_time_seconds / 60,
        distanceKm: group.total_distance_km,
        avgSpeed: group.avg_velocidad,
        startTime: firstRecord.fecha,
        endTime: lastRecord.fecha,
        startPoint: parseCoords(group.start_coords),
        endPoint: parseCoords(group.end_coords),
        records: records,
      };
    }).filter((s: RouteSegment | null): s is RouteSegment => s !== null && s.records.length > 0);

    const routePoints = segments
      .filter(s => s.id_estado === '6') // '6' is "Transitando" (Moving)
      .map(s => s.records.map(r => parseCoords(r.coordenadas)));

    const routeHistory: RouteHistory = { segments, routePoints };

    return NextResponse.json(routeHistory);
  } catch (error) {
    console.error("Error generating route:", error);
    return NextResponse.json({ error: 'Failed to generate route' }, { status: 500 });
  }
}
